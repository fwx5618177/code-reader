// 归类提议接受测试：接受规划（纯函数）与通过知识库服务执行审阅
// ================================

import { beforeEach, describe, expect, it, vi } from 'vitest';
import type {
  ItemCategorizationProposal,
  TagMergeCategorizationProposal,
} from '../../../types/electron';
import type { Tag } from '../../../types/knowledge';
import type { Folder } from '../../folders/types';
import { planItemAcceptance, proposalEdit, type AcceptanceContext } from '../acceptance';

const services = vi.hoisted(() => ({
  listAll: vi.fn(),
  listTags: vi.fn(),
  getAll: vi.fn(),
  update: vi.fn(),
  setItemTags: vi.fn(),
  mergeTags: vi.fn(),
  createFolder: vi.fn(),
  review: vi.fn(),
}));

vi.mock('../../knowledge/repository', () => ({
  knowledgeRepository: {
    listAll: services.listAll,
    listTags: services.listTags,
    update: services.update,
    setItemTags: services.setItemTags,
    mergeTags: services.mergeTags,
  },
}));
vi.mock('../../folders/repository', () => ({ folderRepository: { getAll: services.getAll } }));
vi.mock('../../folders/service', () => ({ folderService: { createFolder: services.createFolder } }));

import { applyReview } from '../review-actions';

const time = new Date(2026, 9, 17);
const folder = (id: string, name: string, parentId: string | null = null): Folder => ({
  id,
  name,
  parentId,
  order: 0,
  createdAt: time,
  updatedAt: time,
});
const tag = (id: string, name: string): Tag => ({
  id,
  name,
  usageCount: 1,
  isAutoGenerated: false,
  createdAt: time,
  updatedAt: time,
});

const FOLDERS = [folder('f1', '工作'), folder('f2', '项目', 'f1'), folder('f3', '读书')];
const TAGS = [tag('t1', 'React'), tag('t2', 'AI')];

const context = (items: Record<string, { folderId?: string; tagIds: string[] }>): AcceptanceContext => ({
  items: new Map(Object.entries(items)),
  tags: TAGS,
  folders: FOLDERS,
});

const itemProposal = (overrides: Partial<ItemCategorizationProposal> = {}): ItemCategorizationProposal => ({
  id: 'p1',
  kind: 'item',
  itemId: 'i1',
  itemTitle: '笔记',
  folderId: 'f2',
  folderName: '工作/项目',
  tags: ['ai', 'Rust'],
  reason: null,
  confidence: 0.8,
  createdAt: '2026-10-17',
  ...overrides,
});

const mergeProposal: TagMergeCategorizationProposal = {
  id: 'pm',
  kind: 'tag-merge',
  sourceTagId: 't9',
  sourceTagName: 'react',
  targetTagId: 't1',
  targetTagName: 'React',
  reason: null,
  confidence: 1,
  createdAt: '2026-10-17',
};

describe('planItemAcceptance', () => {
  const ctx = context({ i1: { tagIds: ['t1'] }, i2: { folderId: 'f3', tagIds: ['t1', 't2'] } });

  it('已有文件夹：移入并追加标签（标签按已有写法，保留条目原有标签）', () => {
    expect(planItemAcceptance(itemProposal(), null, ctx)).toEqual({
      move: { folderId: 'f2' },
      nextTags: ['React', 'AI', 'Rust'],
      applied: { folderId: 'f2', folderName: '工作 / 项目', tags: ['AI', 'Rust'] },
    });
  });

  it('新建文件夹：与已有顶层文件夹同名（忽略大小写）时直接使用，否则新建', () => {
    const reuse = planItemAcceptance(itemProposal({ folderId: null, folderName: '读书 ' }), null, ctx);
    expect(reuse.move).toEqual({ folderId: 'f3' });
    // 子文件夹不参与同名匹配
    const created = planItemAcceptance(itemProposal({ folderId: null, folderName: '项目' }), null, ctx);
    expect(created.move).toEqual({ newFolderName: '项目' });
    expect(created.applied.folderId).toBeNull();
  });

  it('已在目标文件夹且已有全部标签时无需操作，仍记录归类', () => {
    const plan = planItemAcceptance(itemProposal({ itemId: 'i2', folderId: 'f3', tags: ['react'] }), null, ctx);
    expect(plan).toEqual({ move: null, nextTags: null, applied: { folderId: 'f3', folderName: '读书', tags: ['React'] } });
  });

  it('修改后接受：使用编辑后的目标，编辑初始值来自提议', () => {
    expect(proposalEdit(itemProposal({ folderId: null, folderName: '旅行' }))).toEqual({
      folder: { newName: '旅行' },
      tags: ['ai', 'Rust'],
    });
    const plan = planItemAcceptance(itemProposal(), { folder: null, tags: ['Vue', 'vue', ' '] }, ctx);
    expect(plan).toEqual({ move: null, nextTags: ['React', 'Vue'], applied: { folderId: null, folderName: null, tags: ['Vue'] } });
  });

  it('条目已删除、文件夹已不存在、新文件夹名为空、没有任何改动时报错', () => {
    expect(() => planItemAcceptance(itemProposal({ itemId: 'gone' }), null, ctx)).toThrow('条目已被删除');
    expect(() => planItemAcceptance(itemProposal({ folderId: 'deleted' }), null, ctx)).toThrow('已不存在');
    expect(() => planItemAcceptance(itemProposal(), { folder: { newName: '  ' }, tags: [] }, ctx)).toThrow('不能为空');
    expect(() => planItemAcceptance(itemProposal(), { folder: null, tags: [] }, ctx)).toThrow('拒绝');
  });
});

describe('applyReview', () => {
  beforeEach(() => {
    vi.clearAllMocks();
    services.listAll.mockResolvedValue([
      { id: 'i1', folderId: undefined, tagIds: ['t1'] },
      { id: 'i2', folderId: undefined, tagIds: [] },
    ]);
    services.listTags.mockResolvedValue(TAGS);
    services.getAll.mockResolvedValue(FOLDERS);
    services.createFolder.mockResolvedValue(folder('new', '旅行'));
    services.review.mockResolvedValue(undefined);
    vi.stubGlobal('electron', { categorization: { review: services.review } });
  });

  it('先合并标签，再按最新数据应用条目提议；同名新文件夹只创建一次；最后统一记录审阅结果', async () => {
    const travel = { folderId: null, folderName: '旅行' };
    const report = await applyReview([
      { proposal: itemProposal({ ...travel, tags: [] }), accept: true },
      { proposal: itemProposal({ id: 'p2', itemId: 'i2', ...travel, tags: ['AI'] }), accept: true },
      { proposal: mergeProposal, accept: true },
      { proposal: itemProposal({ id: 'p3' }), accept: false },
    ]);

    expect(report).toEqual({ reviewed: 4, failures: [] });
    expect(services.mergeTags).toHaveBeenCalledWith(['t9'], 't1');
    expect(services.mergeTags.mock.invocationCallOrder[0]).toBeLessThan(services.listAll.mock.invocationCallOrder[0]);
    expect(services.createFolder).toHaveBeenCalledTimes(1);
    expect(services.createFolder).toHaveBeenCalledWith({ name: '旅行', parentId: null });
    expect(services.update).toHaveBeenCalledWith('i1', { folderId: 'new' });
    expect(services.update).toHaveBeenCalledWith('i2', { folderId: 'new' });
    expect(services.setItemTags).toHaveBeenCalledTimes(1);
    expect(services.setItemTags).toHaveBeenCalledWith('i2', ['AI']);
    expect(services.review).toHaveBeenCalledWith([
      { id: 'pm', status: 'accepted' },
      { id: 'p3', status: 'rejected' },
      { id: 'p1', status: 'accepted', applied: { folderId: 'new', folderName: '旅行', tags: [] } },
      { id: 'p2', status: 'accepted', applied: { folderId: 'new', folderName: '旅行', tags: ['AI'] } },
    ]);
  });

  it('单条失败不影响其余提议，失败的提议不记录审阅结果', async () => {
    services.mergeTags.mockRejectedValue(new Error('SQLITE_BUSY'));
    const report = await applyReview([
      { proposal: mergeProposal, accept: true },
      { proposal: itemProposal({ folderId: 'deleted' }), accept: true },
      { proposal: itemProposal({ id: 'p2', itemId: 'i2' }), accept: true },
    ]);
    expect(report).toEqual({
      reviewed: 1,
      failures: [
        { proposalId: 'pm', message: 'SQLITE_BUSY' },
        { proposalId: 'p1', message: '目标文件夹已不存在，请修改后接受' },
      ],
    });
    expect(services.review).toHaveBeenCalledWith([
      { id: 'p2', status: 'accepted', applied: { folderId: 'f2', folderName: '工作 / 项目', tags: ['AI', 'Rust'] } },
    ]);
  });

  it('全部失败时不调用主进程', async () => {
    await applyReview([{ proposal: itemProposal({ itemId: 'gone' }), accept: true }]);
    expect(services.review).not.toHaveBeenCalled();
  });
});

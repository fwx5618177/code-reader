import { databaseService, generateId, now, parseJSON } from '../../services/database';
import type {
  KnowledgeItem,
  KnowledgeItemStatus,
  KnowledgeItemType,
  Tag,
} from '../../types/knowledge';

/** knowledge_items 行（列表查询附带标签 ID） */
interface KnowledgeItemRow {
  id: string;
  title: string;
  type: KnowledgeItemType;
  status: KnowledgeItemStatus;
  content: string | null;
  file_path: string | null;
  file_size: number | null;
  mime_type: string | null;
  source_url: string | null;
  summary: string | null;
  key_points: string | null;
  transcript: string | null;
  folder_id: string | null;
  project_id: string | null;
  is_favorite: number;
  is_pinned: number;
  is_indexed: number;
  view_count: number;
  last_viewed_at: string | null;
  metadata: string | null;
  created_at: string;
  updated_at: string;
  tag_ids: string | null;
}

interface TagRow {
  id: string;
  name: string;
  color: string | null;
  icon: string | null;
  parent_id: string | null;
  usage_count: number;
  is_auto_generated: number;
  created_at: string;
  updated_at: string;
}

const ITEM_COLUMNS = `
  k.id, k.title, k.type, k.status, k.content, k.file_path, k.file_size, k.mime_type,
  k.source_url, k.summary, k.key_points, k.transcript, k.folder_id, k.project_id,
  k.is_favorite, k.is_pinned, k.is_indexed, k.view_count, k.last_viewed_at, k.metadata,
  k.created_at, k.updated_at,
  (SELECT GROUP_CONCAT(tag_id) FROM item_tags WHERE item_id = k.id) AS tag_ids`;

function rowToItem(row: KnowledgeItemRow): KnowledgeItem {
  return {
    id: row.id,
    title: row.title,
    type: row.type,
    status: row.status,
    content: row.content ?? undefined,
    filePath: row.file_path ?? undefined,
    fileSize: row.file_size ?? undefined,
    mimeType: row.mime_type ?? undefined,
    sourceUrl: row.source_url ?? undefined,
    summary: row.summary ?? undefined,
    keyPoints: parseJSON<string[] | undefined>(row.key_points, undefined),
    transcript: row.transcript ?? undefined,
    tagIds: row.tag_ids ? row.tag_ids.split(',') : [],
    folderId: row.folder_id ?? undefined,
    projectId: row.project_id ?? undefined,
    isFavorite: row.is_favorite === 1,
    isPinned: row.is_pinned === 1,
    isIndexed: row.is_indexed === 1,
    viewCount: row.view_count,
    lastViewedAt: row.last_viewed_at ? new Date(row.last_viewed_at) : undefined,
    metadata: parseJSON<Record<string, unknown> | undefined>(row.metadata, undefined),
    createdAt: new Date(row.created_at),
    updatedAt: new Date(row.updated_at),
  };
}

function rowToTag(row: TagRow): Tag {
  return {
    id: row.id,
    name: row.name,
    color: row.color ?? undefined,
    icon: row.icon ?? undefined,
    parentId: row.parent_id ?? undefined,
    usageCount: row.usage_count,
    isAutoGenerated: row.is_auto_generated === 1,
    createdAt: new Date(row.created_at),
    updatedAt: new Date(row.updated_at),
  };
}

/** 新建条目输入 */
export interface CreateKnowledgeItemInput {
  id?: string;
  title: string;
  type: KnowledgeItemType;
  content?: string;
  filePath?: string;
  fileSize?: number;
  mimeType?: string;
  sourceUrl?: string;
  folderId?: string;
  metadata?: Record<string, unknown>;
  /** 迁移旧数据时保留原始时间 */
  createdAt?: string;
  updatedAt?: string;
}

/** 可更新字段 */
export interface UpdateKnowledgeItemInput {
  title?: string;
  content?: string;
  summary?: string;
  folderId?: string | null;
  isFavorite?: boolean;
  isPinned?: boolean;
  sourceUrl?: string;
  /** 整体替换元数据（阅读进度等） */
  metadata?: Record<string, unknown>;
}

/** 更新字段 → 列名 */
const UPDATE_COLUMNS: Record<keyof UpdateKnowledgeItemInput, string> = {
  title: 'title',
  content: 'content',
  summary: 'summary',
  folderId: 'folder_id',
  isFavorite: 'is_favorite',
  isPinned: 'is_pinned',
  sourceUrl: 'source_url',
  metadata: 'metadata',
};

class KnowledgeRepository {
  /** 全部未删除条目（按置顶、更新时间排序） */
  async listAll(): Promise<KnowledgeItem[]> {
    const rows = await databaseService.all<KnowledgeItemRow>(
      `SELECT ${ITEM_COLUMNS} FROM knowledge_items k
       WHERE k.is_deleted = 0
       ORDER BY k.is_pinned DESC, k.updated_at DESC`
    );
    return rows.map(rowToItem);
  }

  async getById(id: string): Promise<KnowledgeItem | null> {
    const row = await databaseService.get<KnowledgeItemRow>(
      `SELECT ${ITEM_COLUMNS} FROM knowledge_items k WHERE k.id = ? AND k.is_deleted = 0`,
      [id]
    );
    return row ? rowToItem(row) : null;
  }

  /** 按 ID 批量读取（保持传入顺序） */
  async getByIds(ids: string[]): Promise<KnowledgeItem[]> {
    if (ids.length === 0) return [];
    const placeholders = ids.map(() => '?').join(',');
    const rows = await databaseService.all<KnowledgeItemRow>(
      `SELECT ${ITEM_COLUMNS} FROM knowledge_items k
       WHERE k.id IN (${placeholders}) AND k.is_deleted = 0`,
      ids
    );
    const byId = new Map(rows.map((row) => [row.id, rowToItem(row)]));
    return ids.map((id) => byId.get(id)).filter((item): item is KnowledgeItem => !!item);
  }

  async create(input: CreateKnowledgeItemInput): Promise<KnowledgeItem> {
    const id = input.id ?? generateId();
    const createdAt = input.createdAt ?? now();
    await databaseService.run(
      `INSERT INTO knowledge_items
       (id, title, type, status, content, file_path, file_size, mime_type, source_url,
        folder_id, metadata, created_at, updated_at, is_favorite, is_pinned, is_deleted)
       VALUES (?, ?, ?, 'draft', ?, ?, ?, ?, ?, ?, ?, ?, ?, 0, 0, 0)`,
      [
        id,
        input.title,
        input.type,
        input.content ?? null,
        input.filePath ?? null,
        input.fileSize ?? null,
        input.mimeType ?? null,
        input.sourceUrl ?? null,
        input.folderId ?? null,
        input.metadata ? JSON.stringify(input.metadata) : null,
        createdAt,
        input.updatedAt ?? createdAt,
      ]
    );
    const item = await this.getById(id);
    if (!item) throw new Error(`创建条目失败：${id}`);
    return item;
  }

  async update(id: string, input: UpdateKnowledgeItemInput): Promise<void> {
    const sets: string[] = [];
    const params: unknown[] = [];
    for (const key of Object.keys(input) as (keyof UpdateKnowledgeItemInput)[]) {
      const value = input[key];
      if (value === undefined) continue;
      sets.push(`${UPDATE_COLUMNS[key]} = ?`);
      if (typeof value === 'boolean') params.push(value ? 1 : 0);
      else if (value !== null && typeof value === 'object') params.push(JSON.stringify(value));
      else params.push(value);
    }
    if (sets.length === 0) return;
    // 只更新元数据（如阅读进度）不算内容修改，不刷新更新时间，避免条目在列表中跳到顶部
    const metadataOnly = Object.keys(input).every((key) => key === 'metadata');
    if (!metadataOnly) {
      sets.push('updated_at = ?');
      params.push(now());
    }
    params.push(id);
    await databaseService.run(`UPDATE knowledge_items SET ${sets.join(', ')} WHERE id = ?`, params);
  }

  /** 软删除 */
  async remove(id: string): Promise<void> {
    const timestamp = now();
    await databaseService.run(
      `UPDATE knowledge_items SET is_deleted = 1, deleted_at = ?, updated_at = ? WHERE id = ?`,
      [timestamp, timestamp, id]
    );
  }

  // ================================
  // 标签
  // ================================

  async listTags(): Promise<Tag[]> {
    const rows = await databaseService.all<TagRow>(
      `SELECT id, name, color, icon, parent_id, usage_count, is_auto_generated, created_at, updated_at
       FROM tags WHERE is_deleted = 0
       ORDER BY usage_count DESC, name ASC`
    );
    return rows.map(rowToTag);
  }

  /** 按名称查找标签，不存在时创建 */
  async findOrCreateTag(name: string): Promise<string> {
    const trimmed = name.trim();
    const existing = await databaseService.get<{ id: string }>(
      `SELECT id FROM tags WHERE name = ? AND is_deleted = 0`,
      [trimmed]
    );
    if (existing) return existing.id;
    const id = generateId();
    const timestamp = now();
    await databaseService.run(
      `INSERT INTO tags (id, name, usage_count, is_auto_generated, created_at, updated_at)
       VALUES (?, ?, 0, 0, ?, ?)`,
      [id, trimmed, timestamp, timestamp]
    );
    return id;
  }

  /**
   * 设置条目的标签（替换原有标签），同时维护标签使用次数
   */
  async setItemTags(itemId: string, names: string[]): Promise<void> {
    const uniqueNames = [...new Set(names.map((n) => n.trim()).filter(Boolean))];
    const nextIds = new Set<string>();
    for (const name of uniqueNames) {
      nextIds.add(await this.findOrCreateTag(name));
    }

    const previous = await databaseService.all<{ tag_id: string }>(
      `SELECT tag_id FROM item_tags WHERE item_id = ?`,
      [itemId]
    );
    const previousIds = new Set(previous.map((row) => row.tag_id));
    const timestamp = now();

    for (const tagId of previousIds) {
      if (nextIds.has(tagId)) continue;
      await databaseService.run(`DELETE FROM item_tags WHERE item_id = ? AND tag_id = ?`, [
        itemId,
        tagId,
      ]);
      await databaseService.run(
        `UPDATE tags SET usage_count = MAX(usage_count - 1, 0), updated_at = ? WHERE id = ?`,
        [timestamp, tagId]
      );
    }
    for (const tagId of nextIds) {
      if (previousIds.has(tagId)) continue;
      await databaseService.run(`INSERT OR IGNORE INTO item_tags (item_id, tag_id) VALUES (?, ?)`, [
        itemId,
        tagId,
      ]);
      await databaseService.run(
        `UPDATE tags SET usage_count = usage_count + 1, updated_at = ? WHERE id = ?`,
        [timestamp, tagId]
      );
    }
  }
}

export const knowledgeRepository = new KnowledgeRepository();

import { describe, expect, it } from 'vitest';
import { buildTagTree, tagScopeIds } from '../tag-tree';
import type { Tag } from '../../../types/knowledge';

function tag(id: string, name: string, usageCount = 0): Tag {
  const time = new Date(0);
  return { id, name, usageCount, isAutoGenerated: false, createdAt: time, updatedAt: time };
}

describe('tag-tree', () => {
  it('按层级组织，缺失的父级作为分组，汇总使用次数，同级按名称排序', () => {
    const tree = buildTagTree([
      tag('react', '技术/前端/React', 3),
      tag('vue', '技术/前端/Vue', 1),
      tag('tech', '技术', 2),
      tag('life', '生活', 5),
    ]);
    expect(tree.map((node) => node.label)).toEqual(['技术', '生活']);
    const [tech] = tree;
    expect(tech.tag?.id).toBe('tech');
    expect(tech.totalUsage).toBe(6);
    const [frontend] = tech.children;
    expect(frontend.path).toBe('技术/前端');
    expect(frontend.tag).toBeNull();
    expect(frontend.totalUsage).toBe(4);
    expect(frontend.children.map((node) => node.label)).toEqual(['React', 'Vue']);
  });

  it('筛选范围包含自身与全部子孙', () => {
    const tags = [tag('a', '技术'), tag('b', '技术/前端'), tag('c', '技术/前端/React'), tag('d', '技术栈')];
    expect([...tagScopeIds('a', tags)].sort()).toEqual(['a', 'b', 'c']);
    expect([...tagScopeIds('c', tags)]).toEqual(['c']);
    expect([...tagScopeIds('missing', tags)]).toEqual(['missing']);
  });
});

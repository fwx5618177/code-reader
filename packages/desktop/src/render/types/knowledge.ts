// ================================
// Knowledge Base Data Models
// Phase 1: Core data structures for the intelligent knowledge base
// ================================

// ================================
// Base Entity
// ================================

/**
 * 基础实体接口，所有数据模型都继承此接口
 */
export interface BaseEntity {
  /** 唯一标识符 */
  id: string;
  /** 创建时间 */
  createdAt: Date;
  /** 更新时间 */
  updatedAt: Date;
  /** 是否已删除（软删除） */
  isDeleted?: boolean;
  /** 删除时间 */
  deletedAt?: Date;
}

// ================================
// Knowledge Item (核心数据单元)
// ================================

/**
 * 知识条目类型
 */
export type KnowledgeItemType =
  | 'note' // 笔记
  | 'audio' // 音频/录音
  | 'image' // 图片
  | 'video' // 视频
  | 'document' // 文档 (PDF, Word 等)
  | 'webpage' // 网页剪藏
  | 'code' // 代码片段
  | 'bookmark' // 书签/链接
  | 'file'; // 其他文件

/**
 * 知识条目状态
 */
export type KnowledgeItemStatus =
  | 'draft' // 草稿
  | 'processing' // AI 处理中
  | 'ready' // 就绪
  | 'error'; // 处理出错

/**
 * 知识条目 - 知识库的核心数据单元
 */
export interface KnowledgeItem extends BaseEntity {
  /** 标题 */
  title: string;
  /** 内容类型 */
  type: KnowledgeItemType;
  /** 状态 */
  status: KnowledgeItemStatus;

  // ======= 内容 =======
  /** 原始内容（文本） */
  content?: string;
  /** 原始文件路径（媒体/文档） */
  filePath?: string;
  /** 文件大小（字节） */
  fileSize?: number;
  /** MIME 类型 */
  mimeType?: string;
  /** 来源 URL */
  sourceUrl?: string;

  // ======= AI 处理结果 =======
  /** AI 生成的摘要 */
  summary?: string;
  /** AI 提取的关键点 */
  keyPoints?: string[];
  /** 语音转写文本（音频类型） */
  transcript?: string;
  /** 转写带时间戳 */
  transcriptWithTimestamps?: TranscriptSegment[];

  // ======= 组织 =======
  /** 标签 ID 列表 */
  tagIds: string[];
  /** 所属文件夹 ID */
  folderId?: string;
  /** 项目 ID */
  projectId?: string;
  /** 是否收藏 */
  isFavorite: boolean;
  /** 是否置顶 */
  isPinned: boolean;

  // ======= 搜索与向量 =======
  /** 向量嵌入（用于语义搜索） */
  embedding?: number[];
  /** 全文搜索索引状态 */
  isIndexed: boolean;

  // ======= 统计 =======
  /** 查看次数 */
  viewCount: number;
  /** 最后查看时间 */
  lastViewedAt?: Date;

  // ======= 元数据 =======
  /** 自定义元数据 */
  metadata?: Record<string, unknown>;
}

/**
 * 语音转写片段（带时间戳）
 */
export interface TranscriptSegment {
  /** 开始时间（毫秒） */
  startTime: number;
  /** 结束时间（毫秒） */
  endTime: number;
  /** 文本内容 */
  text: string;
  /** 置信度 (0-1) */
  confidence?: number;
  /** 说话人标识 */
  speaker?: string;
}

// ================================
// Tag (标签)
// ================================

/**
 * 标签
 */
export interface Tag extends BaseEntity {
  /** 标签名称 */
  name: string;
  /** 标签颜色 */
  color?: string;
  /** 标签图标 */
  icon?: string;
  /** 父标签 ID（支持层级） */
  parentId?: string;
  /** 使用次数 */
  usageCount: number;
  /** 是否为 AI 自动生成 */
  isAutoGenerated: boolean;
  /** 同义词/别名 */
  aliases?: string[];
}

// ================================
// Folder (虚拟文件夹)
// ================================

/**
 * 文件夹类型
 */
export type FolderType =
  | 'manual' // 手动创建
  | 'smart' // 智能文件夹（基于规则）
  | 'auto'; // AI 自动生成

/**
 * 虚拟文件夹
 */
export interface Folder extends BaseEntity {
  /** 文件夹名称 */
  name: string;
  /** 文件夹类型 */
  type: FolderType;
  /** 图标 */
  icon?: string;
  /** 颜色 */
  color?: string;
  /** 父文件夹 ID */
  parentId?: string;
  /** 排序顺序 */
  sortOrder: number;
  /** 子项数量 */
  itemCount: number;

  // ======= 智能文件夹规则 =======
  /** 过滤规则（智能文件夹） */
  filterRules?: FilterRule[];
}

/**
 * 过滤规则（用于智能文件夹）
 */
export interface FilterRule {
  /** 字段名 */
  field: string;
  /** 操作符 */
  operator:
    | 'equals'
    | 'notEquals'
    | 'contains'
    | 'notContains'
    | 'startsWith'
    | 'endsWith'
    | 'greaterThan'
    | 'lessThan'
    | 'in'
    | 'notIn'
    | 'isEmpty'
    | 'isNotEmpty';
  /** 值 */
  value: unknown;
}

// ================================
// Link (知识关联)
// ================================

/**
 * 关联类型
 */
export type LinkType =
  | 'reference' // 引用
  | 'related' // 相关
  | 'parent' // 父子关系
  | 'sequence' // 顺序关系
  | 'ai-suggested'; // AI 建议的关联

/**
 * 知识条目之间的关联
 */
export interface Link extends BaseEntity {
  /** 源条目 ID */
  sourceId: string;
  /** 目标条目 ID */
  targetId: string;
  /** 关联类型 */
  type: LinkType;
  /** 关联描述 */
  description?: string;
  /** 关联强度 (0-1) */
  strength?: number;
  /** 是否为双向关联 */
  isBidirectional: boolean;
}

// ================================
// Quick Input (快速输入)
// ================================

/**
 * 快速输入类型
 */
export type QuickInputType =
  | 'text' // 文字笔记
  | 'voice' // 语音录入
  | 'image' // 图片
  | 'file' // 文件
  | 'url'; // 网址

/**
 * 快速输入记录
 */
export interface QuickInputRecord {
  /** 输入类型 */
  type: QuickInputType;
  /** 内容 */
  content: string;
  /** 附件路径 */
  attachments?: string[];
  /** 来源 */
  source?: string;
  /** 时间戳 */
  timestamp: Date;
}

// ================================
// Search (搜索)
// ================================

/**
 * 搜索高亮
 */
export interface SearchHighlight {
  /** 字段名 */
  field: string;
  /** 高亮内容 */
  snippet: string;
  /** 匹配位置 */
  positions?: Array<{ start: number; end: number }>;
}

// ================================
// Settings (设置)
// ================================

/**
 * 应用设置
 */
export interface AppSettings {
  // ======= 通用 =======
  /** 语言 */
  language: 'zh-CN' | 'en-US';
  /** 主题 */
  theme: 'light' | 'dark' | 'system';

  // ======= 存储 =======
  /** 应用数据目录（settings.json 所在）；知识库数据与附件路径由当前知识库决定 */
  dataPath: string;

  // ======= AI =======
  /** 启用 AI 功能 */
  enableAI: boolean;
  /** AI 服务提供商 */
  aiProvider?: 'openai' | 'anthropic' | 'local';
  /** API Key */
  aiApiKey?: string;
  /** 自动转写语音 */
  autoTranscribe: boolean;
  /** 自动生成摘要 */
  autoSummarize: boolean;
  /** 自动打标签 */
  autoTag: boolean;

  // ======= 快速输入 =======
  /** 全局快捷键 */
  quickInputHotkey: string;
  /** 默认输入类型 */
  defaultInputType: QuickInputType;

  // ======= 编辑器 =======
  /** 启用拼写检查（自研 Hunspell 检查器） */
  spellCheck: boolean;
  /** 当前词典 ID（builtin:en_US / user:xx） */
  spellCheckDictionary: string;

  // ======= 同步 =======
  /** 启用同步 */
  enableSync: boolean;
  /** 同步服务 */
  syncProvider?: 'icloud' | 'dropbox' | 'custom';
}

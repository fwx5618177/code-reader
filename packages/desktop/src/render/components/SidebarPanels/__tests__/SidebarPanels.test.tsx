function item(id: string, overrides: Partial<KnowledgeItem> = {}): KnowledgeItem {
  const time = new Date(2026, 9, 17, 9);
  return {
    id,
    title: id,
    type: 'note',
    status: 'ready',
    tagIds: [],
    isFavorite: false,
    isPinned: false,
    isIndexed: false,
    viewCount: 0,
    createdAt: time,
    updatedAt: time,
    ...overrides,
  };
}

function tag(id: string, name: string, usageCount: number): Tag {
  const time = new Date(0);
  return { id, name, usageCount, isAutoGenerated: false, createdAt: time, updatedAt: time };
}


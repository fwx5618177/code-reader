describe('TagCloud', () => {
  it('按使用次数分级显示，点击切换筛选，可清除', () => {
    const onToggleTag = vi.fn();
    const onClearTags = vi.fn();
    const tags = [tag('t1', '常用', 50), tag('t2', '少用', 1)];
    const { rerender } = render(
      <TagCloud tags={tags} selectedTagIds={[]} onToggleTag={onToggleTag} onClearTags={onClearTags} />
    );
    expect(screen.getByRole('button', { name: '常用' }).getAttribute('data-level')).toBe('4');
    expect(screen.getByRole('button', { name: '少用' }).getAttribute('data-level')).toBe('0');

    fireEvent.click(screen.getByRole('button', { name: '少用' }));
    expect(onToggleTag).toHaveBeenCalledWith('t2');

    rerender(<TagCloud tags={tags} selectedTagIds={['t2']} onToggleTag={onToggleTag} onClearTags={onClearTags} />);
    expect(screen.getByRole('button', { name: '少用' }).getAttribute('aria-pressed')).toBe('true');
    fireEvent.click(screen.getByRole('button', { name: /清除/ }));
    expect(onClearTags).toHaveBeenCalled();
  });
});

describe('CalendarPanel', () => {
  beforeEach(() => {
    vi.useFakeTimers({ toFake: ['Date'] });
    vi.setSystemTime(new Date(2026, 9, 17, 10));
  });
  afterEach(() => {
    vi.useRealTimers();
  });

  const items = [
    item('diary', { title: '日记 2026-10-17.md' }),
    item('clip', { title: '剪藏', type: 'webpage' }),
    item('old', { title: '前天的笔记.md', createdAt: new Date(2026, 9, 15, 8) }),
  ];

  function renderCalendar() {
    const props = { onOpenItem: vi.fn(), onOpenDiary: vi.fn(), onCreateDiary: vi.fn() };
    render(<CalendarPanel items={items} {...props} />);
    return props;
  }

  it('标记每天新建的条目数与日记，默认选中今天并列出当日条目', () => {
    const props = renderCalendar();
    expect(screen.getByText('2026 年 10 月')).toBeTruthy();
    const today = screen.getByRole('gridcell', { name: /10 月 17 日/ });
    expect(today.getAttribute('aria-label')).toBe('10 月 17 日，新建 2 个条目，有日记');
    expect(today.getAttribute('aria-selected')).toBe('true');

    const list = screen.getByRole('region', { name: '今天新建的条目' });
    fireEvent.click(within(list).getByRole('button', { name: /剪藏/ }));
    expect(props.onOpenItem).toHaveBeenCalledWith('clip');

    fireEvent.click(screen.getByRole('button', { name: /打开日记/ }));
    expect(props.onOpenDiary).toHaveBeenCalledWith('diary');
  });

  it('选择其他日期可创建当天日记；切换月份与回到今天', () => {
    const props = renderCalendar();
    fireEvent.click(screen.getByRole('gridcell', { name: /10 月 15 日/ }));
    expect(screen.getByText(/10 月 15 日 · 新建 1 个条目/)).toBeTruthy();
    fireEvent.click(screen.getByRole('button', { name: /写这天的日记/ }));
    const [date] = props.onCreateDiary.mock.calls[0];
    expect([date.getFullYear(), date.getMonth(), date.getDate()]).toEqual([2026, 9, 15]);

    fireEvent.click(screen.getByRole('button', { name: '下一月' }));
    expect(screen.getByText('2026 年 11 月')).toBeTruthy();
    fireEvent.click(screen.getByRole('button', { name: '上一月' }));
    fireEvent.click(screen.getByRole('button', { name: '上一月' }));
    expect(screen.getByText('2026 年 9 月')).toBeTruthy();

    fireEvent.click(screen.getByRole('button', { name: '今天' }));
    expect(screen.getByText('2026 年 10 月')).toBeTruthy();
    expect(screen.getByRole('button', { name: /写今天的日记|打开日记/ }).textContent).toContain('打开日记');
  });
});

describe('RecordingsPanel', () => {
  const recordings = [
    item('r1', { title: '周会.webm', type: 'audio', transcript: '讨论', filePath: '/a/周会.webm' }),
    item('r2', {
      title: '灵感',
      type: 'audio',
      status: 'error',
      createdAt: new Date(2026, 9, 16),
      filePath: '/a/灵感.webm',
      metadata: { durationMs: 125_000 },
    }),
    item('n1', { title: '笔记.md' }),
  ];

  function renderPanel() {
    const props = {
      onOpenDetails: vi.fn(),
      onRename: vi.fn(() => Promise.resolve()),
      onDelete: vi.fn(() => Promise.resolve()),
      onUpdateMetadata: vi.fn((_id: string, _metadata: Record<string, unknown>) => Promise.resolve()),
      onError: vi.fn(),
    };
    render(<RecordingsPanel items={recordings} {...props} />);
    return props;
  }

  it('只列出录音，显示时长与转写状态，可打开详情', () => {
    const props = renderPanel();
    expect(screen.getByText('共 2 条录音')).toBeTruthy();
    expect(screen.queryByText('笔记.md')).toBeNull();
    expect(screen.getByText('1:05')).toBeTruthy();
    // 录音时记录了时长的条目直接使用 metadata，不读取音频文件
    expect(screen.getByText('2:05')).toBeTruthy();
    expect(useAudioDuration).not.toHaveBeenCalledWith('/a/灵感.webm', undefined);
    expect(screen.getByText('已转写')).toBeTruthy();
    expect(screen.getByText('转写失败')).toBeTruthy();

    fireEvent.click(screen.getByTitle('周会.webm'));
    expect(props.onOpenDetails).toHaveBeenCalledWith('r1');
  });

  it('没有记录时长的录音读到时长后回填 metadata，已有记录的不写', () => {
    const props = renderPanel();
    expect(props.onUpdateMetadata).toHaveBeenCalledTimes(1);
    expect(props.onUpdateMetadata).toHaveBeenCalledWith('r1', { durationMs: 65_000 });
  });

  it('重命名保留扩展名，删除需确认', () => {
    const props = renderPanel();
    fireEvent.click(screen.getAllByRole('button', { name: '重命名' })[0]);
    fireEvent.change(screen.getByPlaceholderText('请输入录音名称'), { target: { value: '周例会' } });
    fireEvent.click(screen.getByRole('button', { name: '确定' }));
    expect(props.onRename).toHaveBeenCalledWith('r1', '周例会');

    fireEvent.click(screen.getAllByRole('button', { name: '删除' })[1]);
    expect(screen.getByText(/确定删除录音「灵感」吗/)).toBeTruthy();
    fireEvent.click(screen.getAllByRole('button', { name: '删除' }).at(-1)!);
    expect(props.onDelete).toHaveBeenCalledWith('r2');
  });
});

describe('SidebarSearch', () => {
  const hybrid = vi.fn();
  beforeEach(() => {
    vi.useFakeTimers();
    Object.defineProperty(window, 'electron', { configurable: true, value: { search: { hybrid } } });
  });
  afterEach(() => {
    vi.useRealTimers();
  });

  const hit = (itemId: string, title: string): HybridSearchResult =>
    ({ itemId, title, type: 'webpage', snippet: `<mark>${title}</mark>` }) as HybridSearchResult;

  it('复用全局检索，按条件过滤命中，点击打开', async () => {
    searchDocuments.mockResolvedValue([]);
    hybrid.mockResolvedValue([hit('in', '书库里的文章'), hit('out', '书库外的网页')]);
    const onOpenItem = vi.fn();
    render(
      <SidebarSearch placeholder="搜索书库内容" filterHit={(h) => h.id === 'in'} onOpenItem={onOpenItem} />
    );
    fireEvent.change(screen.getByLabelText('搜索书库内容'), { target: { value: '文章' } });
    await act(async () => vi.advanceTimersByTimeAsync(300));

    expect(screen.queryByText('书库外的网页')).toBeNull();
    fireEvent.click(screen.getByRole('button', { name: /书库里的文章/ }));
    expect(onOpenItem).toHaveBeenCalledWith('in');
  });
});

describe('写作侧栏', () => {
  it('大纲按标题层级缩进，点击请求定位标题', () => {
    const onSelectHeading = vi.fn();
    render(<WritingOutline content={'## 背景\n\n正文\n\n### 细节\n'} onSelectHeading={onSelectHeading} />);
    const detail = screen.getByRole('button', { name: '细节' });
    expect(detail.style.getPropertyValue('--outline-depth')).toBe('1');
    fireEvent.click(detail);
    expect(onSelectHeading).toHaveBeenCalledWith('细节', 0);
  });

  it('大纲点击同名标题时传入其在同名标题中的序号', () => {
    const onSelectHeading = vi.fn();
    render(<WritingOutline content={'## 小结\n\n## 其他\n\n## 小结\n'} onSelectHeading={onSelectHeading} />);
    fireEvent.click(screen.getAllByRole('button', { name: '小结' })[1]);
    expect(onSelectHeading).toHaveBeenCalledWith('小结', 1);
  });

  it('标签多选时只列出同时带有这些标签的文档', () => {
    const tags = [tag('t1', '论文', 2), tag('t2', '草稿', 1)];
    const documents = [
      item('d1', { title: '综述.md', tagIds: ['t1'] }),
      item('d2', { title: '初稿.md', tagIds: ['t1', 't2'] }),
    ];
    const onOpenDocument = vi.fn();
    render(<DocumentTags documents={documents} tags={tags} onOpenDocument={onOpenDocument} />);

    fireEvent.click(screen.getByRole('button', { name: /#论文/ }));
    expect(screen.getByRole('button', { name: /综述/ })).toBeTruthy();
    fireEvent.click(screen.getByRole('button', { name: /#草稿/ }));
    expect(screen.queryByRole('button', { name: /综述/ })).toBeNull();
    fireEvent.click(screen.getByRole('button', { name: /初稿/ }));
    expect(onOpenDocument).toHaveBeenCalledWith('d2');
  });
});

import { describe, it, expect } from 'vitest';
import type { Tag } from '../../../types/knowledge';
import { buildTagCloud, TAG_CLOUD_LEVELS } from '../tag-cloud';

function tag(name: string, usageCount: number): Tag {
  const time = new Date(0);
  return { id: name, name, usageCount, isAutoGenerated: false, createdAt: time, updatedAt: time };
}

describe('buildTagCloud', () => {
  it('没有标签时返回空', () => {
    expect(buildTagCloud([])).toEqual([]);
  });

  it('最少使用为最小等级，最多使用为最大等级，结果按名称排序', () => {
    const cloud = buildTagCloud([tag('b', 100), tag('a', 1), tag('c', 10)]);
    expect(cloud.map((entry) => [entry.tag.name, entry.level])).toEqual([
      ['a', 0],
      ['b', TAG_CLOUD_LEVELS - 1],
      ['c', 2],
    ]);
  });

  it('按对数映射：高频标签不会把其余标签都压到最小等级', () => {
    const cloud = buildTagCloud([tag('rare', 0), tag('mid', 30), tag('hot', 1000)]);
    const level = (name: string) => cloud.find((entry) => entry.tag.name === name)!.level;
    expect(level('rare')).toBe(0);
    expect(level('mid')).toBeGreaterThanOrEqual(2);
    expect(level('hot')).toBe(TAG_CLOUD_LEVELS - 1);
  });

  it('次数都相同时取中间等级', () => {
    expect(buildTagCloud([tag('a', 3), tag('b', 3)]).map((entry) => entry.level)).toEqual([2, 2]);
  });
});

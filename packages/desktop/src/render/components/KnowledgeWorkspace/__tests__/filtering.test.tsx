import { describe, expect, it } from 'vitest';
import type { KnowledgeItem, Tag } from '../../../types/knowledge';
import { ITEM_TYPE_LABELS } from '../../ReadingWorkspace/item-type';
import {
  EMPTY_FILTERS,
  UNTAGGED_GROUP,
  applyFilters,
  buildSearchText,
  buildStreamRows,
  dateBucket,
  filterByScope,
  groupItems,
  hasActiveFilters,
  indexStreamRows,
  sortItems,
  stepSelection,
  type GroupOptions,
  type ItemFilters,
} from '../filtering';

function make(id: string, overrides: Partial<KnowledgeItem> = {}): KnowledgeItem {
  const time = new Date(2026, 9, 14, 9);
  return {
    id,
    title: id,
    type: 'note',
    status: 'ready',
    createdAt: time,
    updatedAt: time,
    tagIds: [],
    isFavorite: false,
    isPinned: false,
    isIndexed: false,
    viewCount: 0,
    ...overrides,
  };
}

function tag(id: string, name: string): Tag {
  const time = new Date(0);
  return { id, name, usageCount: 0, isAutoGenerated: false, createdAt: time, updatedAt: time };
}

const TAGS = [tag('t-react', 'React'), tag('t-perf', '性能')];
const tagNameById = new Map(TAGS.map((t) => [t.id, t.name]));
const searchText = (item: KnowledgeItem) => buildSearchText(item, tagNameById);
const filter = (items: KnowledgeItem[], filters: Partial<ItemFilters>) =>
  applyFilters(items, { ...EMPTY_FILTERS, ...filters }, searchText, TAGS);
const ids = (items: KnowledgeItem[]) => items.map((item) => item.id);

// 2026-10-14 是周三，本周从 10-12（周一）开始
const NOW = new Date(2026, 9, 14, 12);

describe('filterByScope', () => {
  it('按文件夹与智能文件夹规则过滤', () => {
    const items = [make('a', { folderId: 'f1' }), make('b', { folderId: 'f2' }), make('c')];
    expect(ids(filterByScope(items, {}))).toEqual(['a', 'b', 'c']);
    expect(ids(filterByScope(items, { folderId: 'f1' }))).toEqual(['a']);
  });
});

describe('applyFilters', () => {
  const items = [
    make('a', { title: 'Hooks 笔记', content: 'useEffect 的清理函数', tagIds: ['t-react'] }),
    make('b', { title: '录音', type: 'audio', transcript: '讨论渲染性能', tagIds: ['t-perf'] }),
    make('c', { title: '网页', type: 'webpage', summary: 'React 性能优化指南', tagIds: ['t-react', 't-perf'] }),
  ];

  it('搜索不区分大小写，覆盖标题、正文、摘要、转写与标签名', () => {
    expect(ids(filter(items, { query: 'HOOKS' }).items)).toEqual(['a']);
    expect(ids(filter(items, { query: '清理函数' }).items)).toEqual(['a']);
    expect(ids(filter(items, { query: '渲染' }).items)).toEqual(['b']);
    expect(ids(filter(items, { query: '优化指南' }).items)).toEqual(['c']);
    // 标签名命中：a 带 React 标签，c 的摘要含 React
    expect(ids(filter(items, { query: 'react' }).items)).toEqual(['a', 'c']);
  });

  it('多个空格分隔的词须全部命中', () => {
    expect(ids(filter(items, { query: 'react  性能' }).items)).toEqual(['c']);
    expect(ids(filter(items, { query: 'hooks 录音' }).items)).toEqual([]);
    expect(ids(filter(items, { query: '   ' }).items)).toEqual(['a', 'b', 'c']);
  });

  it('类型筛选为任一命中，类型计数不受类型筛选影响', () => {
    const result = filter(items, { types: ['audio', 'webpage'] });
    expect(ids(result.items)).toEqual(['b', 'c']);
    expect(Object.fromEntries(result.typeCounts)).toEqual({ note: 1, audio: 1, webpage: 1 });
  });

  it('标签筛选须全部命中，标签计数统计筛选结果', () => {
    const one = filter(items, { tagIds: ['t-react'] });
    expect(ids(one.items)).toEqual(['a', 'c']);
    expect(Object.fromEntries(one.tagCounts)).toEqual({ 't-react': 2, 't-perf': 1 });

    expect(ids(filter(items, { tagIds: ['t-react', 't-perf'] }).items)).toEqual(['c']);
  });

  it('层级标签：按父标签筛选包含子孙标签，子标签的条目计入父标签计数', () => {
    const tags = [tag('t-tech', '技术'), tag('t-fe', '技术/前端'), tag('t-react2', '技术/前端/React'), tag('t-life', '生活')];
    const nested = [
      make('x', { tagIds: ['t-react2'] }),
      make('y', { tagIds: ['t-fe', 't-react2'] }),
      make('z', { tagIds: ['t-tech'] }),
      make('w', { tagIds: ['t-life'] }),
    ];
    const byParent = applyFilters(nested, { ...EMPTY_FILTERS, tagIds: ['t-tech'] }, () => '', tags);
    expect(ids(byParent.items)).toEqual(['x', 'y', 'z']);
    // y 同时带有前端与 React，父标签只计一次
    expect(Object.fromEntries(byParent.tagCounts)).toEqual({ 't-tech': 3, 't-fe': 2, 't-react2': 2 });

    const byMiddle = applyFilters(nested, { ...EMPTY_FILTERS, tagIds: ['t-fe'] }, () => '', tags);
    expect(ids(byMiddle.items)).toEqual(['x', 'y']);
    // “技术/前端工程”之类同前缀但非子级的标签不会被包含
    const sibling = [...tags, tag('t-fe2', '技术/前端工程')];
    const prefixed = applyFilters([make('v', { tagIds: ['t-fe2'] })], { ...EMPTY_FILTERS, tagIds: ['t-fe'] }, () => '', sibling);
    expect(prefixed.items).toEqual([]);
  });

  it('搜索与标签筛选同时作用于类型计数', () => {
    const result = filter(items, { query: '性能', types: ['note'] });
    expect(result.items).toEqual([]);
    expect(Object.fromEntries(result.typeCounts)).toEqual({ audio: 1, webpage: 1 });
  });

  it('hasActiveFilters 忽略空白搜索词', () => {
    expect(hasActiveFilters(EMPTY_FILTERS)).toBe(false);
    expect(hasActiveFilters({ ...EMPTY_FILTERS, query: '  ' })).toBe(false);
    expect(hasActiveFilters({ ...EMPTY_FILTERS, types: ['code'] })).toBe(true);
    expect(hasActiveFilters({ ...EMPTY_FILTERS, tagIds: ['t-perf'] })).toBe(true);
  });
});

describe('sortItems', () => {
  const items = [
    make('old', { title: 'b.md', createdAt: new Date(2026, 0, 3), updatedAt: new Date(2026, 5, 1) }),
    make('pinned', { title: 'z', isPinned: true, createdAt: new Date(2026, 0, 1), updatedAt: new Date(2026, 0, 1) }),
    make('new', { title: 'A', createdAt: new Date(2026, 0, 2), updatedAt: new Date(2026, 8, 1) }),
  ];

  it('置顶条目在前，其余按所选方式排序', () => {
    expect(ids(sortItems(items, 'updated'))).toEqual(['pinned', 'new', 'old']);
    expect(ids(sortItems(items, 'created'))).toEqual(['pinned', 'old', 'new']);
    expect(ids(sortItems(items, 'title'))).toEqual(['pinned', 'new', 'old']);
  });

  it('不修改原数组', () => {
    sortItems(items, 'title');
    expect(ids(items)).toEqual(['old', 'pinned', 'new']);
  });
});

describe('dateBucket', () => {
  it('划分今天 / 昨天 / 本周 / 本月 / 更早', () => {
    expect(dateBucket(new Date(2026, 9, 14, 0, 0), NOW)).toBe('today');
    expect(dateBucket(new Date(2026, 9, 13, 23, 59), NOW)).toBe('yesterday');
    expect(dateBucket(new Date(2026, 9, 12, 8), NOW)).toBe('thisWeek');
    expect(dateBucket(new Date(2026, 9, 11, 8), NOW)).toBe('thisMonth');
    expect(dateBucket(new Date(2026, 8, 30, 8), NOW)).toBe('earlier');
  });

  it('周一时周日算作昨天，上周六算作本月', () => {
    const monday = new Date(2026, 9, 12, 10);
    expect(dateBucket(new Date(2026, 9, 11, 10), monday)).toBe('yesterday');
    expect(dateBucket(new Date(2026, 9, 10, 10), monday)).toBe('thisMonth');
  });
});

describe('groupItems', () => {
  const options: GroupOptions = { sort: 'updated', tags: TAGS, typeLabels: ITEM_TYPE_LABELS, now: NOW };

  it('不分组时输出单个无标题分组，空列表无分组', () => {
    const items = [make('a'), make('b')];
    expect(groupItems(items, 'none', options)).toEqual([{ key: 'all', label: null, items }]);
    expect(groupItems([], 'none', options)).toEqual([]);
  });

  it('按日期分组跟随排序字段，空分组不输出', () => {
    const items = [
      make('a', { createdAt: new Date(2026, 8, 1), updatedAt: new Date(2026, 9, 14, 8) }),
      make('b', { createdAt: new Date(2026, 9, 13, 8), updatedAt: new Date(2026, 9, 13, 9) }),
    ];
    const byUpdated = groupItems(items, 'date', options);
    expect(byUpdated.map((g) => [g.label, ids(g.items)])).toEqual([
      ['今天', ['a']],
      ['昨天', ['b']],
    ]);
    const byCreated = groupItems(items, 'date', { ...options, sort: 'created' });
    expect(byCreated.map((g) => [g.label, ids(g.items)])).toEqual([
      ['昨天', ['b']],
      ['更早', ['a']],
    ]);
  });

  it('按类型分组使用固定类型顺序并保持组内顺序', () => {
    const items = [make('w', { type: 'webpage' }), make('n1'), make('au', { type: 'audio' }), make('n2')];
    expect(groupItems(items, 'type', options).map((g) => [g.label, ids(g.items)])).toEqual([
      [ITEM_TYPE_LABELS.note, ['n1', 'n2']],
      [ITEM_TYPE_LABELS.audio, ['au']],
      [ITEM_TYPE_LABELS.webpage, ['w']],
    ]);
  });

  it('按标签分组时条目出现在每个标签下，无标签与未知标签归入“无标签”', () => {
    const items = [
      make('both', { tagIds: ['t-perf', 't-react'] }),
      make('none'),
      make('unknown', { tagIds: ['deleted-tag'] }),
    ];
    expect(groupItems(items, 'tag', options).map((g) => [g.key, ids(g.items)])).toEqual([
      ['t-react', ['both']],
      ['t-perf', ['both']],
      [UNTAGGED_GROUP, ['none', 'unknown']],
    ]);
  });
});

describe('虚拟列表行与键盘导航', () => {
  const a = make('a');
  const b = make('b');
  const c = make('c');

  it('分组标题单独成行，条目按列数切分', () => {
    const rows = buildStreamRows(
      [
        { key: 'g1', label: '分组一', items: [a, b, c] },
        { key: 'g2', label: '分组二', items: [a] },
      ],
      2
    );
    expect(rows.map((row) => (row.kind === 'header' ? `# ${row.label} ${row.count}` : ids(row.items)))).toEqual([
      '# 分组一 3',
      ['a', 'b'],
      ['c'],
      '# 分组二 1',
      ['a'],
    ]);
  });

  it('无标题分组不生成标题行，列数至少为 1', () => {
    const rows = buildStreamRows([{ key: 'all', label: null, items: [a, b] }], 0);
    expect(rows.map((row) => row.kind)).toEqual(['items', 'items']);
  });

  it('导航顺序去重并记录首次出现的行', () => {
    const rows = buildStreamRows(
      [
        { key: 'g1', label: '一', items: [a, b] },
        { key: 'g2', label: '二', items: [a, c] },
      ],
      1
    );
    const { order, rowOf } = indexStreamRows(rows);
    expect(order).toEqual(['a', 'b', 'c']);
    expect(rowOf.get('a')).toBe(1);
    expect(rowOf.get('c')).toBe(5);
  });

  it('stepSelection 在首尾停住，未选中时从首 / 尾开始', () => {
    const order = ['a', 'b', 'c'];
    expect(stepSelection(order, undefined, 1)).toBe('a');
    expect(stepSelection(order, undefined, -1)).toBe('c');
    expect(stepSelection(order, 'missing', 1)).toBe('a');
    expect(stepSelection(order, 'b', 1)).toBe('c');
    expect(stepSelection(order, 'c', 1)).toBe('c');
    expect(stepSelection(order, 'a', -1)).toBe('a');
    expect(stepSelection([], 'a', 1)).toBeUndefined();
  });
});

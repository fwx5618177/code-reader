import React from 'react';
import { act, fireEvent, render, screen, within } from '@testing-library/react';
import { beforeEach, describe, expect, it, vi } from 'vitest';
import type { KnowledgeItem, Tag } from '../../../types/knowledge';
import type { UseKnowledgeBaseReturn } from '../../../lib/knowledge/useKnowledgeBase';
import { LinkIndex } from '../../../lib/links/link-index';
import { KNOWLEDGE_ITEM_DRAG_TYPE } from '../../../lib/knowledge/drag';
import KnowledgeWorkspace from '..';

vi.mock('../../../lib/agent/agentStore', () => ({
  useAgentActivity: () => [],
  TASK_LABELS: {},
}));
vi.mock('../../../lib/knowledge/service', () => ({ requestProcessing: vi.fn() }));
vi.mock('../../../lib/agent/askService', () => ({ askKnowledgeBase: vi.fn() }));
vi.mock('../../../services/aiConfigService', () => {
  const service = { hasUsableProvider: vi.fn(() => Promise.resolve(false)) };
  return { default: service, aiConfigService: service };
});
// 图谱依赖 canvas，由独立测试覆盖
vi.mock('../../KnowledgeGraph', () => ({ default: () => <div>图谱</div> }));

function make(id: string, overrides: Partial<KnowledgeItem> = {}): KnowledgeItem {
  const time = new Date(2026, 9, 14, 9);
  return {
    id,
    title: id,
    type: 'note',
    status: 'ready',
    createdAt: time,
    updatedAt: time,
    tagIds: [],
    isFavorite: false,
    isPinned: false,
    isIndexed: false,
    viewCount: 0,
    ...overrides,
  };
}

const ITEMS = [
  make('n1', { title: 'React 笔记.md', content: '# 并发渲染\n见 [[性能]]', summary: '并发特性总结' }),
  make('a1', { title: '周会录音', type: 'audio', transcript: '讨论发布计划' }),
];

function makeTag(id: string, name: string, color?: string): Tag {
  const time = new Date(2026, 9, 14, 9);
  return { id, name, color, usageCount: 0, isAutoGenerated: false, createdAt: time, updatedAt: time };
}

/** 标签管理用例：react 与 React 重复，前端已设颜色 */
const TAGS = [makeTag('t1', 'react'), makeTag('t2', 'React'), makeTag('t3', '前端', 'green')];
const TAGGED_ITEMS = [
  make('n1', { title: 'React 笔记.md', tagIds: ['t1', 't3'] }),
  make('n2', { title: 'Hooks.md', tagIds: ['t2'] }),
  make('n3', { title: 'CSS.md', tagIds: ['t2', 't3'] }),
];

function openTagManager(overrides: Partial<UseKnowledgeBaseReturn> = {}) {
  const result = renderWorkspace(TAGGED_ITEMS, undefined, { tags: TAGS, ...overrides });
  fireEvent.click(screen.getByRole('button', { name: '管理标签' }));
  return { ...result, dialog: screen.getByRole('dialog', { name: '管理标签' }) };
}

function kb(
  items: KnowledgeItem[],
  overrides: Partial<UseKnowledgeBaseReturn> = {}
): UseKnowledgeBaseReturn {
  return {
    items,
    tags: [],
    folders: [],
    loading: false,
    error: null,
    reload: vi.fn(() => Promise.resolve()),
    refreshItem: vi.fn(() => Promise.resolve()),
    updateItem: vi.fn(() => Promise.resolve()),
    setItemTags: vi.fn(() => Promise.resolve()),
    removeItem: vi.fn(() => Promise.resolve()),
    createFolder: vi.fn(() => Promise.resolve()),
    renameFolder: vi.fn(() => Promise.resolve()),
    deleteFolder: vi.fn(() => Promise.resolve()),
    renameTag: vi.fn(() => Promise.resolve()),
    mergeTags: vi.fn(() => Promise.resolve()),
    setTagColor: vi.fn(() => Promise.resolve()),
    ...overrides,
  };
}

function renderWorkspace(
  items: KnowledgeItem[],
  selectedItemId?: string,
  kbOverrides: Partial<UseKnowledgeBaseReturn> = {}
) {
  const linkIndex = new LinkIndex();
  linkIndex.update(items);
  const props = {
    kb: kb(items, kbOverrides),
    scope: { label: '全部条目' },
    linkIndex,
    related: [],
    selectedItemId,
    onSelectItem: vi.fn(),
    onOpenInWriting: vi.fn(),
    onCreateNote: vi.fn(),
    onQuickCapture: vi.fn(),
    onOpenSettings: vi.fn(),
  };
  return { props, ...render(<KnowledgeWorkspace {...props} />) };
}

describe('KnowledgeWorkspace', () => {
  beforeEach(() => {
    localStorage.clear();
    vi.stubGlobal(
      'ResizeObserver',
      class {
        observe() {}
        unobserve() {}
        disconnect() {}
      }
    );
    Object.defineProperty(window, 'electron', {
      configurable: true,
      value: { search: { findSimilar: vi.fn(() => Promise.resolve([])) } },
    });
  });

  it('没有条目时显示引导并可快速收集', () => {
    const { props } = renderWorkspace([]);
    fireEvent.click(screen.getByRole('button', { name: /快速收集第一条内容/ }));
    expect(props.onQuickCapture).toHaveBeenCalled();
  });

  it('列出条目，搜索无结果时可清除筛选', () => {
    renderWorkspace(ITEMS);
    expect(screen.getByText('React 笔记')).toBeTruthy();
    expect(screen.getByText('周会录音')).toBeTruthy();

    fireEvent.change(screen.getByLabelText('搜索条目'), { target: { value: '发布 计划' } });
    expect(screen.queryByText('React 笔记')).toBeNull();
    expect(screen.getByText('周会录音')).toBeTruthy();

    fireEvent.change(screen.getByLabelText('搜索条目'), { target: { value: '不存在的内容' } });
    fireEvent.click(screen.getByRole('button', { name: /清除筛选/ }));
    expect(screen.getByText('React 笔记')).toBeTruthy();
  });

  it('点击条目选中，Enter 在写作中打开笔记', () => {
    const { props } = renderWorkspace(ITEMS, 'n1');
    fireEvent.click(screen.getByText('周会录音'));
    expect(props.onSelectItem).toHaveBeenCalledWith('a1');

    fireEvent.keyDown(screen.getByRole('region'), { key: 'Enter' });
    expect(props.onOpenInWriting).toHaveBeenCalledWith('n1');
  });

  it('详情面板显示 AI 摘要，原始内容中的未创建链接触发新建笔记', () => {
    const { props } = renderWorkspace(ITEMS, 'n1');
    expect((screen.getByLabelText('标题') as HTMLInputElement).value).toBe('React 笔记');
    expect(screen.getAllByText('并发特性总结').length).toBeGreaterThan(0);

    fireEvent.click(screen.getByRole('tab', { name: '原始内容' }));
    fireEvent.click(screen.getByText('性能'));
    expect(props.onCreateNote).toHaveBeenCalledWith('性能');
  });

  it('修改标题后失焦保存并保留扩展名，Esc 撤销', () => {
    const { props } = renderWorkspace(ITEMS, 'n1');
    const input = screen.getByLabelText('标题') as HTMLInputElement;

    fireEvent.change(input, { target: { value: 'Hooks 笔记' } });
    fireEvent.blur(input);
    expect(props.kb.updateItem).toHaveBeenCalledWith('n1', { title: 'Hooks 笔记.md' });

    fireEvent.change(input, { target: { value: '不保存' } });
    fireEvent.keyDown(input, { key: 'Escape' });
    fireEvent.blur(input);
    expect(props.kb.updateItem).toHaveBeenCalledTimes(1);
    expect(input.value).toBe('React 笔记');
  });

  it('问答视图在没有可用服务商时引导打开设置', async () => {
    const { props } = renderWorkspace(ITEMS);
    fireEvent.click(screen.getByRole('tab', { name: /问答/ }));
    await act(async () => {});
    fireEvent.click(screen.getByRole('button', { name: /打开设置/ }));
    expect(props.onOpenSettings).toHaveBeenCalled();
  });

  it('详情面板通过文件夹选择移动条目，选「未归档」移出文件夹', () => {
    const time = new Date(2026, 9, 14, 9);
    const folders = [{ id: 'f1', name: '工作', parentId: null, order: 0, createdAt: time, updatedAt: time }];
    const { props } = renderWorkspace([make('n1', { folderId: 'f1' })], 'n1', { folders });
    const select = screen.getByLabelText('移动到文件夹') as HTMLSelectElement;
    expect(select.value).toBe('f1');

    fireEvent.change(select, { target: { value: '' } });
    expect(props.kb.updateItem).toHaveBeenCalledWith('n1', { folderId: null });
  });

  it('标签管理列出标签及条目数，Esc 关闭', () => {
    const { dialog } = openTagManager();
    const rows = within(dialog).getAllByRole('listitem');
    expect(rows.map((row) => row.textContent)).toEqual(['React2', '前端2', 'react1']);

    fireEvent.keyDown(dialog, { key: 'Escape' });
    expect(screen.queryByRole('dialog', { name: '管理标签' })).toBeNull();
  });

  it('行内重命名：同名时提示将合并，Esc 取消不保存', async () => {
    const { props, dialog } = openTagManager();

    fireEvent.click(within(dialog).getByRole('button', { name: 'react' }));
    const input = within(dialog).getByLabelText('重命名标签「react」');
    fireEvent.change(input, { target: { value: '前端' } });
    expect(within(dialog).getByText(/已存在「前端」，保存后将合并/)).toBeTruthy();
    // 等待重命名写入完成，名称按钮恢复可点击
    await act(async () => {
      fireEvent.keyDown(input, { key: 'Enter' });
    });
    expect(props.kb.renameTag).toHaveBeenCalledWith('t1', '前端');

    fireEvent.click(within(dialog).getByRole('button', { name: 'React' }));
    const second = within(dialog).getByLabelText('重命名标签「React」');
    fireEvent.change(second, { target: { value: '不保存' } });
    fireEvent.keyDown(second, { key: 'Escape' });
    expect(props.kb.renameTag).toHaveBeenCalledTimes(1);
    // Esc 只取消编辑，对话框仍打开
    expect(screen.getByRole('dialog', { name: '管理标签' })).toBeTruthy();
  });

  it('勾选多个标签后合并到选定目标', async () => {
    const { props, dialog } = openTagManager();
    fireEvent.click(within(dialog).getByLabelText('选择标签「react」'));
    fireEvent.click(within(dialog).getByLabelText('选择标签「React」'));
    fireEvent.change(within(dialog).getByLabelText('合并目标'), { target: { value: 't2' } });

    await act(async () => {
      fireEvent.click(within(dialog).getByRole('button', { name: /合并$/ }));
    });
    expect(props.kb.mergeTags).toHaveBeenCalledWith(['t1'], 't2');
  });

  it('从调色板设置或清除标签颜色', () => {
    const { props, dialog } = openTagManager();
    fireEvent.click(within(dialog).getByLabelText('设置「react」的颜色'));
    fireEvent.click(within(dialog).getByRole('button', { name: '蓝' }));
    expect(props.kb.setTagColor).toHaveBeenCalledWith('t1', 'blue');

    fireEvent.click(within(dialog).getByLabelText('设置「前端」的颜色'));
    expect(within(dialog).getByRole('button', { name: '绿' }).getAttribute('aria-pressed')).toBe('true');
    fireEvent.click(within(dialog).getByRole('button', { name: /无颜色/ }));
    expect(props.kb.setTagColor).toHaveBeenCalledWith('t3', null);
  });

  it('条目可拖动，拖动数据携带条目 ID', () => {
    renderWorkspace(ITEMS);
    const entry = screen.getByText('周会录音').closest('[draggable="true"]') as HTMLElement;
    const setData = vi.fn();
    fireEvent.dragStart(entry, { dataTransfer: { setData, effectAllowed: '' } });
    expect(setData).toHaveBeenCalledWith(KNOWLEDGE_ITEM_DRAG_TYPE, 'a1');
  });
});
